// Generates supabase/migrations/*_seed_team_leads.sql from design/roadmap-mock.html.
//
// Runs the mock's own roster logic (mtRoster): one lead per project team,
// picked from the dev-lead name pool by hash, skipping anyone already on the
// project. Pool names not yet in the people directory are added (fictional,
// first.last@ibm.com, no Slack handle). Usage:
//   node scripts/seed/generate-team-leads-seed.mjs > supabase/migrations/<ts>_seed_team_leads.sql

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const html = readFileSync(path.join(root, "design/roadmap-mock.html"), "utf8");
const slice = (a, b) => {
  const i = html.indexOf(a), j = html.indexOf(b, i);
  if (i < 0 || j < 0) throw new Error(`Mock changed: ${a} .. ${b}`);
  return html.slice(i, j);
};
const data = slice("var PHASES = [", "var EDITS = {};").replace(/var TODAY = new Date\(\)\.toISOString\(\)\.slice\(0,10\);/, 'var TODAY = "2026-09-22";');
const roster = slice("function mtRoster(p){", "function mtInvited(");
const mock = new Function(`"use strict";\n${data}\nvar record = baseRecord;\n${roster}\nreturn { P, POOL, ROLES, baseRecord, mtRoster };`)();

const sql = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const email = (n) => n.toLowerCase().replace(/[^a-z\s-]/g, "").trim().split(/\s+/).join(".") + "@ibm.com";

const leads = [];
const names = new Set();
for (const p of mock.P) {
  const r = mock.mtRoster(p).filter((x) => x.key === "team");
  p.teams.forEach((t, i) => {
    leads.push([p.id, t, r[i].name]);
    names.add(r[i].name);
  });
}

const out = [`-- Liftoff: project team leads seed.
-- GENERATED by scripts/seed/generate-team-leads-seed.mjs from design/roadmap-mock.html
-- (mtRoster). Do not edit by hand; regenerate instead.
`];
out.push(`insert into public.people (display_name, email)
select v.name, v.email
from (values
${[...names].sort().map((n) => `  (${sql(n)}, ${sql(email(n))})`).join(",\n")}
) as v(name, email)
where not exists (select 1 from public.people pe where lower(pe.display_name) = lower(v.name));
`);
out.push(`update public.project_teams pt
set lead_person_id = pe.id
from (values
${leads.map(([k, t, n]) => `  (${sql(k)}, ${sql(t)}, ${sql(n)})`).join(",\n")}
) as v(project_key, team_name, lead_name)
join public.projects p on p.key = v.project_key
join public.teams t on t.name = v.team_name
join public.people pe on lower(pe.display_name) = lower(v.lead_name)
where pt.project_id = p.id and pt.team_id = t.id;
`);
process.stdout.write(out.join("\n"));
console.error(`${leads.length} team leads, ${names.size} distinct names`);
