// Generates supabase/migrations/*_seed_lifecycle.sql from design/roadmap-mock.html.
//
// Cuts TL_STAGES and TL_ITEMS verbatim from the mock and writes the lifecycle
// template, then initialises every existing project: a project_lifecycle row
// with all scopes on, and "Change control (if needed)" as N/A. Nothing is
// marked done.
//
// Usage: node scripts/seed/generate-lifecycle-seed.mjs > supabase/migrations/<ts>_seed_lifecycle.sql

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const html = readFileSync(path.join(root, "design/roadmap-mock.html"), "utf8");

function slice(startMarker, endMarker) {
  const start = html.indexOf(startMarker);
  const end = html.indexOf(endMarker, start);
  if (start < 0 || end < 0) throw new Error(`Mock changed: cannot find ${startMarker} .. ${endMarker}`);
  return html.slice(start, end);
}

const code = slice("var TL_STAGES = [", "var TL_PHASE_WEEK");
const { TL_STAGES, TL_ITEMS } = new Function(`"use strict";\n${code}\nreturn { TL_STAGES, TL_ITEMS };`)();

const TYPE = { gate: "gate", ms: "milestone", task: "task", rec: "weekly" };
const sql = (v) => (v === null || v === undefined ? "null" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

const out = [];
out.push(`-- Liftoff: lifecycle template seed.
-- GENERATED by scripts/seed/generate-lifecycle-seed.mjs from design/roadmap-mock.html
-- (TL_STAGES and TL_ITEMS). Do not edit by hand; regenerate instead.
`);

out.push("insert into public.lifecycle_stages (position, name, duration_label, start_week, end_week) values");
out.push(TL_STAGES.map((s, i) => `  (${i + 1}, ${sql(s[0])}, ${sql(s[1])}, ${s[2]}, ${s[3]})`).join(",\n") + ";\n");

out.push("insert into public.lifecycle_items (id, name, track, type, start_week, end_week, scope, position) values");
out.push(
  TL_ITEMS.map(
    (it, i) =>
      `  (${sql(it.id)}, ${sql(it.name)}, ${sql(it.track)}, ${sql(TYPE[it.type])}, ${it.s}, ${it.e}, ${sql(it.scope)}, ${i + 1})`,
  ).join(",\n") + ";\n",
);

out.push(`-- Existing projects: all scopes on, every item open except change control.
insert into public.project_lifecycle (project_id)
select id from public.projects
on conflict do nothing;

insert into public.project_lifecycle_items (project_id, item_id, status)
select p.id, 'chg', 'na' from public.projects p
on conflict do nothing;
`);

process.stdout.write(out.join("\n"));
